# -*- coding: utf-8 -*-
import os
from pathlib import Path

def auto_load_env():
    env_p = Path(__file__).resolve().parent / ".env"
    if env_p.exists():
        for line in env_p.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip().strip("'\"")
                if k and k not in os.environ:
                    os.environ[k] = v

auto_load_env()
